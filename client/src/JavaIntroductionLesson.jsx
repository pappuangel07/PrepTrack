      <section style={sectionStyle}>
        <h2>12. Interview Questions and Answers</h2>

        <details>
          <summary>1. What is Java?</summary>
          <p>
            Java is a high-level, class-based programming language
            that compiles source code into bytecode executed by
            a compatible JVM.
          </p>
        </details>

        <details>
          <summary>2. Why is Java platform independent?</summary>
          <p>
            Java compiles into bytecode rather than directly into
            machine code for one operating system. A compatible JVM
            can execute that bytecode on different platforms.
          </p>
        </details>

        <details>
          <summary>3. What is the difference between JDK and JVM?</summary>
          <p>
            JVM executes bytecode. JDK provides development tools,
            including the compiler, and runtime components.
          </p>
        </details>

        <details>
          <summary>4. Is Java fully object-oriented?</summary>
          <p>
            Java is object-oriented, but it is not considered purely
            object-oriented because it supports primitive types such
            as int, char, and boolean.
          </p>
        </details>

        <details>
          <summary>5. What is bytecode?</summary>
          <p>
            Bytecode is the intermediate instruction format generated
            by the Java compiler and executed by the JVM.
          </p>
        </details>

        <details>
          <summary>6. What is the role of the main method?</summary>
          <p>
            It is the conventional entry point used by the Java
            launcher to start a standard Java application.
          </p>
        </details>

        <details>
          <summary>7. Does Java use a compiler or interpreter?</summary>
          <p>
            Java uses compilation to generate bytecode. The JVM
            can interpret bytecode and use Just-In-Time compilation
            to compile frequently executed code into machine code.
          </p>
        </details>

        <details>
          <summary>8. What is garbage collection?</summary>
          <p>
            Garbage collection automatically reclaims memory occupied
            by objects that are no longer reachable.
          </p>
        </details>

        <details>
          <summary>9. Can Java have memory leaks?</summary>
          <p>
            Yes. Objects that are no longer needed can remain reachable
            through references, preventing garbage collection.
          </p>
        </details>

        <details>
          <summary>10. What is the difference between compile-time and runtime errors?</summary>
          <p>
            Compile-time errors are detected while compiling source
            code. Runtime errors occur during program execution.
          </p>
        </details>
      </section>

